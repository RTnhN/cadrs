#!/usr/bin/env python3
"""Converts SMLib's fillet tests (NVIDIA usd-brep, tests/prog_test/src/smFilletTest.cpp,
Apache-2.0) into crates/cadrs_kernel/tests/smlib_fillets.rs: each case reads its model
(tests/data/smlib), fillets (or chamfers) the edges SMLib's test names by index, and checks the
result is a valid solid with the edge count SMLib's test asserts. Known failures
(tools/smlib_known_failures.txt) must still fail.

usage: tools/smlib_fillets.py <usd-brep checkout>"""
import os, re, shutil, sys

root = sys.argv[1]
src = open(os.path.join(root, "tests/prog_test/src/smFilletTest.cpp")).read()
here = os.path.dirname(os.path.abspath(__file__))
crate = os.path.join(here, "../crates/cadrs_kernel")
data = os.path.join(crate, "tests/data/smlib")
os.makedirs(data, exist_ok=True)
# Known failures: `name` (must still fail) or `name slow` (runs only with --ignored: it takes
# minutes or never finishes).
known, slow = set(), set()
kf = os.path.join(here, "smlib_known_failures.txt")
if os.path.exists(kf):
    for line in open(kf):
        w = line.split()
        if w and not w[0].startswith("#"):
            known.add(w[0])
            if "slow" in w[1:]:
                slow.add(w[0])

blocks = re.split(r"\n\s*if \(lCount == (\d+)\)\s*\n", src)
cases = []
for i in range(1, len(blocks), 2):
    n = int(blocks[i])
    b = blocks[i + 1]
    cut = b.find("\n  if (lCount ==")
    if cut >= 0:
        b = b[:cut]
    f = re.search(r"Fillet/([A-Za-z0-9_]+\.smb)", b)
    r = re.search(r"dBallRadius\s*=\s*([0-9.eE+-]+)", b)
    k = re.search(r"lNumIntervals\s*=\s*(\d+)", b)
    e = re.search(r"lTotalEdges\s*==\s*(\d+)", b)
    call = re.search(r"my_test_model\((.*?)\)\);", b, re.S)
    if not (f and r and k and e and call):
        continue
    flags = re.findall(r"\b(TRUE|FALSE)\b", call.group(1))
    chamfer = len(flags) >= 2 and flags[-2] == "TRUE"
    ivs = dict((int(a), int(v)) for a, v in re.findall(r"aIndexArr\[\s*(\d+)\]\s*=\s*(\d+)", b))
    idx = [(ivs[2 * j], ivs[2 * j + 1]) for j in range(int(k.group(1))) if 2 * j + 1 in ivs]
    include = "EXCLUDE_ARRAY" not in call.group(1)
    cases.append((n, f.group(1), float(r.group(1)), idx, include, chamfer, int(e.group(1))))

out = [
    "//! SMLib's fillet tests (NVIDIA usd-brep `tests/prog_test/src/smFilletTest.cpp`, Apache-2.0;",
    "//! models in `tests/data/smlib`) on the native kernel: the edges a case names by index (SMLib's",
    "//! file order, matched by their middle points), filleted (or chamfered) at its radius, must give",
    "//! a valid solid with the edge count SMLib asserts. Generated by `tools/smlib_fillets.py`; known",
    "//! failures (`tools/smlib_known_failures.txt`) must still fail.",
    "#![allow(clippy::all)]",
    "",
    "mod smlib {",
    "    use cadrs_kernel::native::{smb, NativeKernel};",
    "    use cadrs_kernel::{ChamferSpec, EdgeId, Kernel};",
    "",
    "    /// Reads `file`, blends the named edges (index ranges, all others when `include` is false)",
    "    /// and checks validity and the edge count.",
    "    pub fn case(file: &str, radius: f64, ranges: &[(usize, usize)], include: bool, chamfer: bool, edges: usize) -> Result<(), String> {",
    "        let path = format!(\"{}/tests/data/smlib/{file}\", env!(\"CARGO_MANIFEST_DIR\"));",
    "        let (body, mids, _) = smb::read_with_edges(&std::fs::read(&path).map_err(|e| e.to_string())?)?;",
    "        let picked: Vec<usize> = (0..mids.len()).filter(|i| ranges.iter().any(|&(a, b)| (a..=b).contains(i)) == include).collect();",
    "        // Each named edge: the body's edge nearest its middle point.",
    "        let mut ids = Vec::new();",
    "        for i in picked {",
    "            let m = mids[i];",
    "            let best = (0..body.edges.len()).filter(|&e| !body.edges[e].degenerate).min_by(|&a, &b| {",
    "                let d = |e: usize| { let ed = &body.edges[e]; let t = ed.curve.closest(&m, ed.t[0], ed.t[1]); (ed.point(t) - m).norm() };",
    "                d(a).total_cmp(&d(b))",
    "            }).ok_or(\"no edges\")?;",
    "            if !ids.contains(&EdgeId(best as u64)) { ids.push(EdgeId(best as u64)); }",
    "        }",
    "        let mut k = NativeKernel::new();",
    "        let b = k.insert(body);",
    "        let r = if chamfer { k.chamfer(b, &ids, ChamferSpec::EqualDistance(radius)) } else { k.fillet(b, &ids, radius) }.map_err(|e| format!(\"{e:?}\"))?;",
    "        let out = k.get(r.bodies[0]).map_err(|e| format!(\"{e:?}\"))?;",
    "        let issues = out.check();",
    "        if !issues.is_empty() { return Err(format!(\"invalid: {}\", issues[0])); }",
    "        let n = out.edges.iter().filter(|e| !e.degenerate).count();",
    "        if n != edges { return Err(format!(\"{n} edges, SMLib gives {edges}\")); }",
    "        Ok(())",
    "    }",
    "}",
]
used = set()
for (n, f, r, idx, inc, ch, e) in cases:
    name = f"case_{n:03}_{f[:-4].lower()}"
    used.add(f)
    rs = ", ".join(f"({a}, {b})" for a, b in idx)
    call = f'smlib::case("{f}", {r!r}, &[{rs}], {str(inc).lower()}, {str(ch).lower()}, {e})'
    out.append("")
    out.append(f"/// SMLib fillet test {n}: `{f}`, {'chamfer' if ch else 'radius'} {r}, edges {'' if inc else 'all but '}{idx}.")
    out.append("#[test]")
    if name in known:
        if name in slow:
            out.append('#[ignore = "known failure, slow (tools/smlib_known_failures.txt)"]')
        out.append(f"fn {name}() {{")
        out.append(f"    assert!({call}.is_err(), \"a known failure now passes: remove `{name}` from tools/smlib_known_failures.txt\");")
        out.append("}")
    else:
        out.append(f"fn {name}() {{")
        out.append(f"    {call}.unwrap();")
        out.append("}")
for f in sorted(used):
    shutil.copy(os.path.join(root, "TestFiles/pt_TestFiles/Fillet", f), data)
open(os.path.join(data, "README.md"), "w").write(
    "SMLib B-rep models from NVIDIA's usd-brep (https://github.com/NVIDIA-Omniverse/usd-brep,\n"
    "`TestFiles/pt_TestFiles/Fillet`), Copyright (c) 2020-2026 NVIDIA CORPORATION & AFFILIATES, licensed\n"
    "under the Apache License 2.0 (http://www.apache.org/licenses/LICENSE-2.0). Unmodified. Used by\n"
    "`tests/smlib_fillets.rs` (generated by `tools/smlib_fillets.py`).\n")
open(os.path.join(crate, "tests/smlib_fillets.rs"), "w").write("\n".join(out) + "\n")
print(f"{len(cases)} cases, {len(used)} models")
